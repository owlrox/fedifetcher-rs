#!/bin/sh
# Regenerate CHANGELOG.md from the commit history: one section per
# version, newest first, holding the write-up (commit message) of every
# commit that carried that version. A commit's version is the (x.y.z)
# suffix of its subject, or — for commits written before that convention
# (everything below 1.0.5) — the version in the Cargo.toml committed
# with it. See AGENTS.md, Versioning.
set -eu
cd "$(dirname "$0")"

# Fallback versions: hash <US> version <US> per commit.
map=$(mktemp)
trap 'rm -f "$map"' EXIT
git log --format='%h %s' | while IFS="
" read -r line; do
    hash=${line%% *}
    subject=${line#* }
    case "$subject" in
    *")") ;;
    *)
        v=$(git show "$hash:Cargo.toml" 2>/dev/null |
            sed -n 's/^version = "\(.*\)"/\1/p' | head -n 1)
        printf '%s\037%s\036' "$hash" "$v" >>"$map"
        ;;
    esac
done

git log --format='%h%x1f%s%x1f%b%x1e' |
awk '
    BEGIN { FS = "\037"; RS = "\036"; ORS = "" }
    FNR == NR { if ($1 != "") ver[$1] = $2; next }
    NF < 3 { next }
    {
        # git terminates each entry with a newline after the record
        # separator, and that newline lands at the start of the next
        # record. Strip it before splitting.
        sub(/^\n+/, "", $0)
        hash = $1; subject = $2; body = $3

        v = ""
        if (match(subject, /\([0-9]+\.[0-9]+\.[0-9]+\)$/)) {
            v = substr(subject, RSTART + 1, RLENGTH - 2)
            subject = substr(subject, 1, RSTART - 1)
        } else if (hash in ver) {
            v = ver[hash]
        }
        sub(/ +$/, "", subject)

        # Drop the commit trailer and surrounding blank lines from the
        # body; the write-up itself stays verbatim.
        n = split(body, line, "\n")
        while (n > 0 && (line[n] == "" ||
                         line[n] ~ /^Generated by / ||
                         line[n] ~ /^Co-Authored-By: /))
            n--
        body = ""
        for (i = 1; i <= n; i++) body = body line[i] "\n"
        sub(/^\n+/, "", body)
        sub(/\n+$/, "", body)

        # The two upstream-versioned commits predate the project own
        # versioning; give them one heading instead of "8.2.3".
        heading = v == "8.2.3" ? "Early development (pre-1.0.3)" : v

        if (heading != curver) {
            curver = heading
            printf "%s## %s\n\n", (started ? "\n" : ""), heading
            started = 1
        } else {
            printf "\n"
        }

        if (subject ~ /[.!:?]$/) printf "%s\n", subject
        else printf "%s.\n", subject
        if (body != "") printf "\n%s\n", body
    }
' "$map" - >CHANGELOG.md

echo "Wrote $(wc -l <CHANGELOG.md | tr -d ' ') lines to CHANGELOG.md"
